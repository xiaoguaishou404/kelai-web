function seededResource(
  base: Omit<Resource, "draftContent" | "publishedContent" | "reviewHistory" | "rights">,
  content: ResourceContent,
): Resource {
  return {
    ...base,
    draftContent: clone(content),
    publishedContent: clone(content),
    reviewHistory: [],
    rights: seededRights(base.id),
  };
}

